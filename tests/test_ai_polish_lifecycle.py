"""[MINI-COMMENT: ASSISTANT.POLISH.LIFECYCLE.TESTS]
[EN rev.1]
[Role] Exercises title concurrency, receipt durability and per-item bulk boundaries with synthetic Linux data.
[Dependencies] The established real-route AssistantTests fixture; no production application import or model request.
[Impact] A rename cannot cross accounts, erase a later title, restart jobs or lose its manual marker after maintenance.
"""
from concurrent.futures import ThreadPoolExecutor
import os
import time
import unittest
import uuid

from assistant_fixture_tests import AssistantTests
from utils.ai_assistant.policy import AssistantError
from utils.ai_assistant.store import Store


@unittest.skipUnless(os.name == 'posix', 'Linux-only isolated behavior fixtures')
class PolishLifecycleTests(unittest.TestCase):
    setUp = AssistantTests.setUp
    connect = AssistantTests.connect
    login = AssistantTests.login
    conversation = AssistantTests.conversation
    submit = AssistantTests.submit
    claim = AssistantTests.claim
    finish = AssistantTests.finish

    def rename(self, cid, title, previous='새 대화', revision=0, operation=None, **extra):
        """[Role] Sends the exact browser CAS payload with a stable optional synthetic operation identity."""
        return self.client.post('/api/ai/conversations/' + cid + '/rename', json=dict(
            title=title, expected_title=previous, lifecycle_revision=revision,
            operation_id=operation or uuid.uuid4().hex, **extra), headers=self.headers)

    def lifecycle(self, cid, action, revision, operation=None):
        """[Role] Calls the unchanged per-item endpoint used by the sequential bulk client."""
        return self.client.post('/api/ai/conversations/' + cid + '/' + action,
            json={'lifecycle_revision': revision, 'operation_id': operation or uuid.uuid4().hex}, headers=self.headers)

    def metadata(self, cid, view='active'):
        """[Role] Reads current server metadata without opening any production database."""
        return self.client.get('/api/ai/conversations/' + cid + '/messages?view=' + view).get_json()['conversation']

    def test_rename_owner_admin_menu_origin_csrf_and_closed_body(self):
        """[Role] Checks real auth boundaries, including an administrator attempting another owner's title."""
        cid = self.conversation()
        for uid in (3, 1):
            self.login(uid)
            self.assertEqual(self.rename(cid, '다른 계정').status_code, 404)
        self.login(2)
        body = dict(title='이름', expected_title='새 대화', lifecycle_revision=0, operation_id=uuid.uuid4().hex)
        self.assertEqual(self.client.post('/api/ai/conversations/' + cid + '/rename', json=body).status_code, 403)
        self.assertEqual(self.client.post('/api/ai/conversations/' + cid + '/rename', json=body,
            headers={'Origin': 'https://other.example', 'X-CSRFToken': 'fixture-csrf'}).status_code, 403)
        self.assertEqual(self.rename(cid, '이름', owner=3).status_code, 400)
        self.assertEqual(self.rename(cid, '이름', revision=True).status_code, 409)
        with self.connect() as db:
            db.execute("INSERT OR REPLACE INTO role_menu_permissions(Role,MenuCode,IsAllowed,UpdatedAt) VALUES('user','equipment_ai',0,'fixture')")
        self.assertEqual(self.rename(cid, '이름').status_code, 403)

    def test_title_validation_preserves_plain_unicode_and_literal_markup(self):
        """[Role] Rejects malformed/control titles and measures emoji by code points while retaining text-only markup."""
        cid = self.conversation()
        for invalid in ('', '   ', 'a' * 101, 'line\nbreak', '\tname', 'x\x00', 'x\x7f', 'x\u2028', 'x\u2029', 'x\u202e', 'x\ud800', None, [], {}, False):
            with self.subTest(invalid=repr(invalid)):
                self.assertNotEqual(self.rename(cid, invalid).status_code, 200)
        title = '😀' * 100
        result = self.rename(cid, title)
        self.assertEqual(result.status_code, 200, result.get_json())
        self.assertEqual(result.get_json()['conversation']['title'], title)
        markup = '<img src=x onerror=alert(1)> & 안전한 이름'
        result = self.rename(cid, '  ' + markup + '  ', previous=title, revision=1)
        self.assertEqual(result.status_code, 200, result.get_json())
        self.assertEqual(self.metadata(cid)['title'], markup)

    def test_manual_default_title_survives_restart_old_receipt_and_cleanup(self):
        """[Role] Prevents the exact default title from being autogenerated again, even after aged receipt maintenance/restart."""
        cid = self.conversation()
        result = self.rename(cid, '새 대화')
        self.assertEqual(result.status_code, 200, result.get_json())
        with self.store.db(True) as db:
            db.execute('UPDATE ai_lifecycle_operations SET created=? WHERE conversation=?', (time.time() - 365 * 86400, cid))
        self.store.purge_expired()
        Store(self.store.path, epoch=self.store.epoch)
        jid = self.submit(cid, content='이 질문을 자동 제목으로 바꾸면 안 됩니다.')
        self.assertEqual(self.metadata(cid)['title'], '새 대화')
        with self.store.db() as db:
            self.assertEqual(db.execute('SELECT state FROM jobs WHERE id=?', (jid,)).fetchone()[0], 'queued')
            receipt = db.execute('SELECT action FROM ai_lifecycle_operations WHERE conversation=?', (cid,)).fetchone()[0]
        self.assertTrue(receipt.startswith('rename:'))
        self.assertNotIn('새 대화', receipt)

    def test_automatic_title_and_lifecycle_changes_reject_stale_rename(self):
        """[Role] Covers the auto-title race that is invisible to lifecycle_revision alone, then a concurrent trash."""
        cid = self.conversation()
        self.submit(cid, content='자동으로 붙인 제목')
        self.assertEqual(self.rename(cid, '편집 중이던 이름').status_code, 409)
        result = self.rename(cid, '직접 정한 이름', previous='자동으로 붙인 제목')
        self.assertEqual(result.status_code, 200, result.get_json())
        self.assertEqual(self.lifecycle(cid, 'trash', 0).status_code, 409)
        moved = self.lifecycle(cid, 'trash', 1)
        self.assertEqual(moved.status_code, 200, moved.get_json())
        self.assertNotEqual(self.rename(cid, '휴지통에서 수정', previous='직접 정한 이름', revision=2).status_code, 200)

    def test_replayed_rename_returns_current_title_then_no_title_after_purge(self):
        """[Role] Keeps idempotent receipts content-free and prevents a lost ACK retry from overwriting later edits."""
        cid, operation = self.conversation(), uuid.uuid4().hex
        first = self.rename(cid, '첫 이름', operation=operation)
        self.assertEqual(first.status_code, 200, first.get_json())
        self.assertEqual(self.rename(cid, '다른 payload', operation=operation).status_code, 409)
        second = self.rename(cid, '현재 이름', previous='첫 이름', revision=1)
        self.assertEqual(second.status_code, 200, second.get_json())
        replay = self.rename(cid, '첫 이름', operation=operation).get_json()
        self.assertTrue(replay['replayed'])
        self.assertEqual(replay['conversation']['title'], '현재 이름')
        self.assertEqual(replay['conversation']['lifecycle_revision'], 2)
        self.assertEqual(self.lifecycle(cid, 'trash', 2).status_code, 200)
        with self.store.db(True) as db:
            deleted = time.time() - 31 * 86400
            db.execute('UPDATE conversations SET deleted_at=?,purge_after=? WHERE id=?', (deleted, deleted + 30 * 86400, cid))
        expired = self.rename(cid, '첫 이름', operation=operation).get_json()
        self.assertTrue(expired['expired'])
        self.assertFalse(expired['purged'])
        self.assertNotIn('title', expired['conversation'])
        self.assertEqual(self.client.get('/api/ai/conversations/' + cid + '/messages?view=trash').status_code, 410)
        self.assertEqual(self.lifecycle(cid, 'purge', 3).status_code, 200)
        replay = self.rename(cid, '첫 이름', operation=operation).get_json()
        self.assertTrue(replay['purged'])
        self.assertNotIn('title', replay['conversation'])

    def test_concurrent_store_renames_have_one_cas_winner_without_job_changes(self):
        """[Role] Serializes simultaneous tabs on the real writer and confirms active jobs are not cancelled by naming."""
        cid = self.conversation()
        jid = self.submit(cid, content='실행 중인 대화')
        job = self.claim()
        metadata = self.metadata(cid)
        with self.store.db() as db:
            account = db.execute('SELECT account_key FROM conversations WHERE id=?', (cid,)).fetchone()[0]

        def attempt(title):
            """[Role] Gives each synthetic tab an independent transaction and records only its public conflict status."""
            try:
                return self.store.rename_conversation(2, cid, account, title, metadata['title'], 0, uuid.uuid4().hex)
            except AssistantError as error:
                return error.status

        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(attempt, ['동시 이름 하나', '동시 이름 둘']))
        self.assertEqual(sum(isinstance(value, dict) for value in results), 1)
        self.assertIn(409, results)
        with self.store.db() as db:
            row = db.execute('SELECT state,cancel FROM jobs WHERE id=?', (jid,)).fetchone()
        self.assertEqual(tuple(row), ('running', 0))
        self.finish(job, content='이름을 바꾸어도 기존 응답을 완료합니다.')

    def test_bulk_per_item_expiry_owner_and_revision_failures_do_not_undo_success(self):
        """[Role] Verifies partial bulk behavior remains independently authorized with exact server retention and replay rules."""
        success, expired, stale = [self.conversation() for _ in range(3)]
        for cid in (success, expired, stale):
            self.assertEqual(self.lifecycle(cid, 'trash', 0).status_code, 200)
        with self.store.db(True) as db:
            now = time.time() - 31 * 86400
            db.execute('UPDATE conversations SET deleted_at=?,purge_after=? WHERE id=?', (now, now + 30 * 86400, expired))
        operation = uuid.uuid4().hex
        self.assertEqual(self.lifecycle(success, 'restore', 1, operation).status_code, 200)
        self.assertEqual(self.lifecycle(expired, 'restore', 1).status_code, 410)
        self.assertEqual(self.lifecycle(stale, 'restore', 0).status_code, 409)
        self.login(3)
        self.assertEqual(self.lifecycle(stale, 'purge', 1).status_code, 404)
        self.login(2)
        self.assertTrue(self.lifecycle(success, 'restore', 1, operation).get_json()['replayed'])
        moved = self.lifecycle(success, 'trash', 2).get_json()['conversation']
        self.assertEqual(moved['purge_after'] - moved['deleted_at'], 30 * 86400)
        self.assertGreater(moved['deleted_at'], self.metadata(stale, 'trash')['deleted_at'])
        self.assertIsNone(self.metadata(success, 'trash').get('owner'))
